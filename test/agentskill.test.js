// The agent skill: the package's how-to plus this instance's setup, written where the agent reads skills
// and kept current by the engine.
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("fs");
const os = require("os");
const path = require("path");
const { execFileSync } = require("child_process");
const agentskill = require("../lib/agentskill");
const { resolve } = require("../lib/instance");

const BIN = path.join(__dirname, "..", "bin", "watchhub.js");
const instance = () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "watchhub-askill-"));
  fs.writeFileSync(path.join(dir, "instance.json"), JSON.stringify({ probes: { jobs: true }, scopes: [{ name: "web", prBase: "^main" }], defaultScope: "all", agentNotes: ["Tell Sam in one line per burst.", "Lane inboxes: web-lane."] }));
  for (const d of ["plans", "watches", "sinks"]) fs.mkdirSync(path.join(dir, d));
  fs.writeFileSync(path.join(dir, "plans", "web.json"), JSON.stringify({ name: "web", scope: "web", on: [{ match: "^MERGED", do: "deploy" }], skill: "watchhub-plan-web" }));
  fs.writeFileSync(path.join(dir, "watches", "app-log.json"), JSON.stringify({ name: "app-log", scope: "web", file: { path: "x.log" } }));
  fs.writeFileSync(path.join(dir, "sinks", "chat.json"), JSON.stringify({ name: "chat", http: { url: "https://example.com/hook" } }));
  return resolve(dir);
};

test("the skill is the package's how-to followed by this instance: notes, sources, watches, scopes, plans, sinks", () => {
  const inst = instance(), t = agentskill.text(inst);
  assert.ok(t.startsWith(fs.readFileSync(path.join(__dirname, "..", "skills", "watchhub", "SKILL.md"), "utf8").trimEnd()));
  assert.match(t, /\n## This instance\n\nGenerated by watchhub from this machine's instance\. /);
  assert.ok(!t.includes(inst.dir), "no machine path in the text");
  assert.match(t, /\*\*Notes for agents\*\* \(`agentNotes` in `instance.json`\):\n- Tell Sam in one line per burst\.\n- Lane inboxes: web-lane\.\n/);
  assert.match(t, /\*\*Sources:\*\* [^\n]*`jobs`/);
  assert.match(t, /\*\*Watches\*\* \(probe `custom:<name>`\): `app-log` \(file, scope web\)\./);
  assert.match(t, /\*\*Scopes:\*\* `web`; lines that match none are `all`\./);
  assert.match(t, /- `web`: scope web; 1 rule; codes in skill `watchhub-plan-web`/);
  assert.match(t, /\*\*Sinks:\*\* `chat`\./);
});

test("install writes the skill, remembers the folder, and refresh follows the config and forgets a removed folder", () => {
  const inst = instance(), home = fs.mkdtempSync(path.join(os.tmpdir(), "watchhub-askill-home-"));
  const dir = path.join(home, ".claude", "skills", "watchhub");
  assert.equal(agentskill.install(inst, dir), path.join(dir, "SKILL.md"));
  agentskill.install(inst, dir);
  assert.deepEqual(JSON.parse(fs.readFileSync(inst.paths.agentSkills, "utf8")).map((e) => e.dir), [dir]);
  const cfg = JSON.parse(fs.readFileSync(inst.paths.config, "utf8"));
  cfg.agentNotes = "Faults go to the watcher session.";
  fs.writeFileSync(inst.paths.config, JSON.stringify(cfg));
  const logs = [];
  agentskill.refresh(inst, (m) => logs.push(m));
  assert.match(fs.readFileSync(path.join(dir, "SKILL.md"), "utf8"), /- Faults go to the watcher session\.\n/);
  assert.deepEqual(logs, [`agent skill rewritten in ${dir}`]);
  agentskill.refresh(inst, (m) => logs.push(m));
  assert.equal(logs.length, 1, "an unchanged skill is not rewritten");
  // someone else changes the file (a person, another instance): left alone and forgotten; install takes it back
  fs.writeFileSync(path.join(dir, "SKILL.md"), "hand edited\n");
  agentskill.refresh(inst, (m) => logs.push(m));
  assert.equal(fs.readFileSync(path.join(dir, "SKILL.md"), "utf8"), "hand edited\n");
  assert.match(logs[1], /changed by someone else; no longer kept current/);
  assert.deepEqual(JSON.parse(fs.readFileSync(inst.paths.agentSkills, "utf8")), []);
  agentskill.install(inst, dir);
  assert.match(fs.readFileSync(path.join(dir, "SKILL.md"), "utf8"), /## This instance/);
  fs.rmSync(dir, { recursive: true });
  agentskill.refresh(inst, (m) => logs.push(m));
  assert.ok(!fs.existsSync(dir), "a removed copy is not brought back");
  assert.match(logs[2], /gone; no longer kept current/);
  assert.deepEqual(JSON.parse(fs.readFileSync(inst.paths.agentSkills, "utf8")), []);
});

test("the package's own skill folder is never overwritten", () => {
  assert.throws(() => agentskill.install(instance(), path.join(__dirname, "..", "skills", "watchhub")), /package's own skill folder/);
});

test("hook install writes the hooks and the skill; skill prints it, and --out takes a leading ~", () => {
  const inst = instance(), home = fs.mkdtempSync(path.join(os.tmpdir(), "watchhub-askill-home-"));
  const run = (...args) => execFileSync(process.execPath, [BIN, ...args, "--instance", inst.dir], { encoding: "utf8", windowsHide: true, env: { ...process.env, HOME: home, USERPROFILE: home } });
  const out = run("hook", "install", "~");
  const f = path.join(home, ".claude", "skills", "watchhub", "SKILL.md");
  assert.ok(out.includes(path.join(home, ".claude", "settings.json")) && out.includes(f), out);
  assert.match(fs.readFileSync(f, "utf8"), /Tell Sam in one line per burst/);
  assert.equal(run("skill"), agentskill.text(inst));
  run("skill", "--out", "~/agent/skills/watchhub");
  assert.ok(fs.existsSync(path.join(home, "agent", "skills", "watchhub", "SKILL.md")));
  assert.equal(JSON.parse(fs.readFileSync(inst.paths.agentSkills, "utf8")).length, 2);
});

test("a broken agent-skills.json is read as empty, and non-string notes are written as JSON", () => {
  const inst = instance();
  fs.writeFileSync(inst.paths.agentSkills, JSON.stringify({ not: "a list" }));
  agentskill.refresh(inst, () => assert.fail("nothing to refresh"));
  const cfg = JSON.parse(fs.readFileSync(inst.paths.config, "utf8"));
  cfg.agentNotes = [{ lane: "web" }];
  fs.writeFileSync(inst.paths.config, JSON.stringify(cfg));
  assert.match(agentskill.text(inst), /\n- \{"lane":"web"\}\n/);
});

test("hook install without an instance still writes the hooks and says how to get the skill", () => {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), "watchhub-askill-home-")), cwd = fs.mkdtempSync(path.join(os.tmpdir(), "watchhub-askill-cwd-"));
  const env = { ...process.env, HOME: home, USERPROFILE: home };
  delete env.WATCHHUB_INSTANCE; delete env.WATCHHUB_HOME;
  const out = execFileSync(process.execPath, [BIN, "hook", "install", "~"], { encoding: "utf8", windowsHide: true, env, cwd });
  assert.ok(fs.existsSync(path.join(home, ".claude", "settings.json")));
  assert.match(out, /skill not written: no instance\.json in .*Run watchhub init <folder>, then watchhub hook install again/);
  assert.ok(!fs.existsSync(path.join(home, ".claude", "skills")));
});
