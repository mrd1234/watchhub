// The agent skill: the package's skills/watchhub/SKILL.md (how watchhub works) plus a section built from
// this instance (its sources, scopes, plans, sinks and the team's agentNotes), so an agent on any machine
// learns the tool and this setup from one file. `watchhub hook install` and `watchhub skill --out` write
// it; each folder is remembered in <instance>/agent-skills.json (machine-local) with a hash of what was
// written, and the engine rewrites it when the instance changes or the engine is upgraded. A copy that
// someone else changed since (a person, or another instance writing the same folder) is left alone and
// forgotten, so two writers never take turns rewriting one file.
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");
const sources = require("./sources");
const plans = require("./plans");
const sinks = require("./sinks");
const { readJson, expandHome } = require("./util");

const BASE = path.join(__dirname, "..", "skills", "watchhub");
const list = (xs) => xs.map((x) => `\`${x}\``).join(", ");
const hash = (t) => crypto.createHash("sha256").update(t).digest("hex");
const same = (a, b) => (process.platform === "win32" ? a.toLowerCase() === b.toLowerCase() : a === b);

// `code` is the engine's loaded code sources; the CLI loads them itself. Nothing machine-specific (no
// path, no version) goes in, so the text depends only on the config.
function instanceSection(inst, code) {
  const cfg = inst.config();
  const out = ["", "## This instance", "",
    "Generated by watchhub from this machine's instance. The engine rewrites this file when the instance or watchhub changes, so change `instance.json` (`agentNotes`), the plans, watches or sinks rather than editing it.", ""];
  const notes = [].concat(cfg.agentNotes || []).map((n) => (typeof n === "string" ? n : JSON.stringify(n)));
  if (notes.length) out.push("**Notes for agents** (`agentNotes` in `instance.json`):", ...notes.map((n) => `- ${n}`), "");
  const on = (p) => { try { return p.enabled(cfg); } catch { return false; } };
  const names = (code || sources.allCode(inst.paths.modules, () => {})).filter(on).map((p) => p.name);
  if (names.length) out.push(`**Sources:** ${list(names)}.`, "");
  const ws = sources.loadWatches(inst.paths.watches);
  if (ws.length) out.push(`**Watches** (probe \`custom:<name>\`): ${ws.map((w) => w.invalid ? `\`${w.name}\` (invalid)` : `\`${w.name}\` (${sources.kindOf(w)[0]}${w.scope ? `, scope ${w.scope}` : ""})`).join(", ")}.`, "");
  const scopes = (cfg.scopes || []).map((s) => s.name).filter(Boolean);
  if (scopes.length) out.push(`**Scopes:** ${list(scopes)}; lines that match none are \`${cfg.defaultScope || "all"}\`.`, "");
  const ps = plans.list(inst.paths.plans);
  if (ps.length) {
    out.push("**Plans** (`watchhub sub <inbox> --plan <name>`):");
    for (const p of ps) {
      const n = (p.on || []).length;
      out.push(p.invalid ? `- \`${p.name}\`: invalid (${p.invalid})` : `- \`${p.name}\`: ${[p.scope ? `scope ${p.scope}` : "", p.probes ? `probes ${p.probes.join(", ")}` : "", `${n} rule${n === 1 ? "" : "s"}`, p.skill ? `codes in skill \`${p.skill}\`` : ""].filter(Boolean).join("; ")}`);
    }
    out.push("");
  }
  const sk = Object.keys(sinks.load(inst.paths.sinks).sinks);
  if (sk.length) out.push(`**Sinks:** ${list(sk)}.`, "");
  return out.join("\n");
}

const text = (inst, code) => fs.readFileSync(path.join(BASE, "SKILL.md"), "utf8").replace(/\s*$/, "\n") + instanceSection(inst, code);

const known = (inst) => { const k = readJson(inst.paths.agentSkills, []); return Array.isArray(k) ? k.filter((e) => e && typeof e.dir === "string") : []; };
const save = (inst, k) => fs.writeFileSync(inst.paths.agentSkills, JSON.stringify(k, null, 2) + "\n");

// Write the skill into <dir> (taking the folder back if another writer had it) and remember it.
function install(inst, dir) {
  const d = path.resolve(expandHome(dir)), real = (p) => { try { return fs.realpathSync(p); } catch { return path.resolve(p); } };
  if (same(real(d), real(BASE))) throw new Error(`${d} is the package's own skill folder; write the generated skill somewhere else`);
  const t = text(inst), f = path.join(d, "SKILL.md");
  fs.mkdirSync(d, { recursive: true });
  if (!fs.existsSync(f) || fs.readFileSync(f, "utf8") !== t) fs.writeFileSync(f, t);
  save(inst, [...known(inst).filter((e) => !same(e.dir, d)), { dir: d, sha: hash(t) }]);
  return f;
}

// The engine's side: rewrite every remembered copy whose text is out of date. A folder that is gone,
// or a file changed by someone else since it was written, is forgotten (one log line), never fought over.
function refresh(inst, log, code) {
  const k = known(inst);
  if (!k.length) return;
  const t = text(inst, code), sha = hash(t), keep = [];
  for (const e of k) {
    const f = path.join(e.dir, "SKILL.md");
    try {
      if (!fs.existsSync(f)) { log(`agent skill ${f} gone; no longer kept current`); continue; }
      const cur = hash(fs.readFileSync(f, "utf8"));
      if (cur !== e.sha && cur !== sha) { log(`agent skill ${f} changed by someone else; no longer kept current (watchhub skill --out ${e.dir} takes it back)`); continue; }
      if (cur !== sha) { fs.writeFileSync(f, t); log(`agent skill rewritten in ${e.dir}`); }
      keep.push({ dir: e.dir, sha });
    } catch (err) { log(`agent skill ${f}: ${err.message}`); keep.push(e); }
  }
  if (JSON.stringify(keep) !== JSON.stringify(k)) save(inst, keep);
}

module.exports = { text, install, refresh };
